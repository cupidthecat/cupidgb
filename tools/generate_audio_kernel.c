#include <inttypes.h>
#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

enum { PHASES = 256, TAPS = 64, GRID = PHASES * TAPS };

static double integral[GRID + 1];
static int32_t coefficients[PHASES][TAPS];

static void generate(void) {
    const double pi = acos(-1.0);
    for (unsigned point = 0; point < GRID; ++point) {
        const double distance = (double)point / PHASES - TAPS / 2.0;
        const double angle = pi * (15.0 / 16.0) * distance;
        const double sinc = angle == 0 ? 1 : sin(angle) / angle;
        const double cycle = 2.0 * pi * point / GRID;
        const double window = (7938.0 - 9240.0 * cos(cycle) + 1430.0 * cos(2 * cycle)) / 18608.0;
        integral[point + 1] = integral[point] + sinc * window;
    }
    const double scale = 65536.0 / integral[GRID];
    for (unsigned phase = 0; phase < PHASES; ++phase) {
        int64_t total = 0;
        for (unsigned tap = 0; tap < TAPS; ++tap) {
            const int begin = (int)(tap * PHASES) - (int)phase;
            const int end = begin + PHASES;
            const unsigned low = begin < 0 ? 0u : (unsigned)begin;
            const unsigned high = end < 0 ? 0u : (unsigned)end;
            const double area = (integral[high] - integral[low]) * scale;
            if (!isfinite(area) || area < INT32_MIN || area > INT32_MAX) {
                fputs("The generated coefficient is outside int32.\n", stderr);
                exit(1);
            }
            coefficients[phase][tap] = (int32_t)area;
            total += coefficients[phase][tap];
        }
        /* Preserve exactly one unit of settled DC gain after quantization. */
        coefficients[phase][TAPS / 2] += (int32_t)(65536 - total);
    }
}

static int write_bank(FILE *output) {
    fputs(
        "/**\n * @file    audio_kernel.inc\n * @brief   Generated fixed-point coefficients for "
        "channel reconstruction.\n * @author  cupidthecat\n * @date    2026-11-16\n *\n * "
        "Generated by tools/generate_audio_kernel.c. Do not edit by hand.\n *\n * "
        "Copyright (C) 2026 cupidthecat\n *\n * This program is free software: you can "
        "redistribute it and/or modify\n * it under the terms of the GNU General Public License as "
        "published by\n * the Free Software Foundation, either version 3 of the License, or\n * "
        "(at your option) any later version.\n *\n * This program is distributed in the hope that "
        "it will be useful,\n * but WITHOUT ANY WARRANTY; without even the implied warranty of\n * "
        "MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE. See the\n * GNU General Public "
        "License for more details.\n *\n * You should have received a copy of the GNU General "
        "Public License\n * along with this program. If not, see <https://gnu.org>.\n */\n",
        output);
    fputs("static const int32_t audio_kernel[CUPID_GB_AUDIO_PHASES][CUPID_GB_AUDIO_TAPS] = {\n",
          output);
    for (unsigned phase = 0; phase < PHASES; ++phase) {
        fputs("    {\n        ", output);
        unsigned column = 8;
        for (unsigned tap = 0; tap < TAPS; ++tap) {
            char value[24];
            const int length =
                snprintf(value, sizeof(value), "%" PRId32 ",", coefficients[phase][tap]);
            if (length < 0 || (size_t)length >= sizeof(value))
                return 1;
            if (column + (unsigned)length + 1 > 100) {
                fputs("\n        ", output);
                column = 8;
            } else if (column > 8) {
                fputc(' ', output);
                ++column;
            }
            fputs(value, output);
            column += (unsigned)length;
        }
        fputs("\n    },\n", output);
    }
    fputs("};\n", output);
    return ferror(output) ? 1 : 0;
}

int main(int argc, char **argv) {
    if (argc != 2) {
        fputs("Usage: generate_audio_kernel NEW_OUTPUT_PATH\n", stderr);
        return 2;
    }
    generate();
    FILE *output = fopen(argv[1], "wbx");
    if (!output) {
        perror(argv[1]);
        return 1;
    }
    const int failed = write_bank(output);
    const int close_failed = fclose(output);
    return failed || close_failed ? 1 : 0;
}
