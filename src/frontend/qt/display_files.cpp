#include "display_files.h"

#include <QBuffer>
#include <QDir>
#include <QFile>
#include <QFileInfo>
#include <QSaveFile>

namespace {
constexpr char paletteSignature[] = {'L', 'P', 'B', 'S'};

QByteArray screenshotBytes(const QImage &image, QString *error) {
    QByteArray bytes;
    QBuffer buffer(&bytes);
    if (image.isNull() || !buffer.open(QIODevice::WriteOnly) || !image.save(&buffer, "PNG")) {
        if (error)
            *error = "Could not encode the screenshot as PNG.";
        return {};
    }
    return bytes;
}
} // namespace

bool decodeDisplayPalette(const QByteArray &bytes, DisplayPaletteFile &palette) {
    if (bytes.size() < 17 || bytes.first(4) != QByteArray(paletteSignature, 4))
        return false;
    const auto flags = static_cast<unsigned char>(bytes[4]);
    if ((flags & 2u) && bytes.size() < 20)
        return false;
    DisplayPaletteFile candidate;
    for (size_t shade = 0; shade < candidate.shades.size(); ++shade) {
        const qsizetype offset = 5 + qsizetype(3 - shade) * 3;
        candidate.shades[shade] = qRgb(static_cast<unsigned char>(bytes[offset]),
                                       static_cast<unsigned char>(bytes[offset + 1]),
                                       static_cast<unsigned char>(bytes[offset + 2]));
    }
    // Full files contain resolved colors even when generated by an automatic palette editor.
    // Older four-color files share the lightest shade with the disabled LCD.
    candidate.off = bytes.size() >= 20 ? qRgb(static_cast<unsigned char>(bytes[17]),
                                              static_cast<unsigned char>(bytes[18]),
                                              static_cast<unsigned char>(bytes[19]))
                                       : candidate.shades[0];
    palette = candidate;
    return true;
}

QByteArray encodeDisplayPalette(const DisplayPaletteFile &palette) {
    QByteArray bytes(paletteSignature, 4);
    bytes.append(char(3)); // Explicit colors and a separate disabled-LCD sample.
    auto appendColor = [&bytes](QRgb color) {
        bytes.append(char(qRed(color)));
        bytes.append(char(qGreen(color)));
        bytes.append(char(qBlue(color)));
    };
    for (auto shade = palette.shades.rbegin(); shade != palette.shades.rend(); ++shade)
        appendColor(*shade);
    appendColor(palette.off);
    return bytes;
}

QString saveTimestampedScreenshot(const QImage &image, const QString &cartridge,
                                  const QDateTime &time, QString *error) {
    if (error)
        error->clear();
    if (cartridge.isEmpty() || !time.isValid()) {
        if (error)
            *error = "No cartridge path or valid capture time is available.";
        return {};
    }
    const QByteArray bytes = screenshotBytes(image, error);
    if (bytes.isEmpty())
        return {};
    const QFileInfo source(cartridge);
    const QString stem = source.completeBaseName() + ' ' + time.toString("yyyy-MM-dd HH.mm.ss");
    // Exclusive creation closes the existence-check race and keeps earlier captures intact.
    for (unsigned index = 1; index <= 10000; ++index) {
        const QString suffix = index == 1 ? QString() : QString(" %1").arg(index);
        const QString path = source.dir().filePath(stem + suffix + ".png");
        QFile output(path);
        if (!output.open(QIODevice::WriteOnly | QIODevice::NewOnly)) {
            if (QFileInfo::exists(path))
                continue;
            if (error)
                *error = output.errorString();
            return {};
        }
        if (output.write(bytes) != bytes.size() || !output.flush()) {
            if (error)
                *error = output.errorString();
            output.remove();
            return {};
        }
        return path;
    }
    if (error)
        *error = "Too many screenshots already use this capture time.";
    return {};
}

bool saveScreenshotFile(const QImage &image, const QString &path, QString *error) {
    if (error)
        error->clear();
    const QByteArray bytes = screenshotBytes(image, error);
    if (bytes.isEmpty())
        return false;
    QSaveFile output(path);
    if (!output.open(QIODevice::WriteOnly) || output.write(bytes) != bytes.size() ||
        !output.commit()) {
        if (error)
            *error = output.errorString();
        return false;
    }
    return true;
}
